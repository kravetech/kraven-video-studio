// Generate tokens from the bundled, self-contained preset.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
const input = process.argv[2] ?? 'presets/default.tokens.json';
const raw = readFileSync(input,'utf8');
const vars = JSON.parse(raw);
for (const [name,value] of Object.entries(vars)) if (typeof value !== 'string') throw new Error(`Invalid token: ${name}`);
const source = {system:'Kraven Minimal',sha256:createHash('sha256').update(raw).digest('hex')};
writeFileSync('src/design-system/tokens.generated.ts',`// GENERATED by scripts/sync-design-system.mjs. Do not edit by hand.\nexport const dsSource = ${JSON.stringify(source,null,2)} as const;\nexport const cssVars = ${JSON.stringify(vars,null,2)} as const;\nexport type CssVar = keyof typeof cssVars;\n`);
console.log(`Generated ${Object.keys(vars).length} tokens from ${input}`);
